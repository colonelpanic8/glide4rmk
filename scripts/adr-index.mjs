// Builds the table of decisions in docs/adr/README.md from the records themselves:
// each one's number and file, its `# NNNN. Title` and its `**Status:**` line.
// Never edit the table by hand; on a merge conflict in it, take either side and run
// `npm run docs`. src/architecture/adr-index.test.ts fails when it is stale.
//   node scripts/adr-index.mjs           write the table
//   node scripts/adr-index.mjs --check   exit 1 if the table is stale or a record is malformed
//   … --dir <folder>                     another folder of records (for the test)
//
// The Status column is the Status line's first sentence, without parentheses,
// then any later clause that names a record this one was changed by
// ("amended by 0024", "replaced by 0021"), so a reader sees where to go next.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dirArg = process.argv.indexOf("--dir");
const DIR = dirArg > 0 ? path.resolve(process.argv[dirArg + 1]) : fileURLToPath(new URL("../docs/adr/", import.meta.url));
const README = path.join(DIR, "README.md");
const START = "<!-- adr-index: generated by `npm run docs`; do not edit by hand -->";
const END = "<!-- /adr-index -->";

const LATER = /^.*?\b(?:amended|replaced|superseded|completed|extended|refined|designed) by (?:ADR )?\d{4}\b/i;

/** The Status column for a record's Status line. */
function shortStatus(line) {
  const text = line.replace(/\s*\([^)]*\)/g, "").trim();
  const sentences = text.split(/(?<=\.)\s+(?=[A-Z`])/);
  const first = sentences[0].replace(/\.$/, "");
  const parts = [first];
  for (const sentence of sentences.slice(1)) {
    for (const clause of sentence.split(/;\s*/)) {
      const short = clause.match(LATER)?.[0].trim();
      if (short) parts.push(short.charAt(0).toLowerCase() + short.slice(1));
    }
  }
  return parts.join("; ");
}

/** Every record, read and checked; problems instead of records when one is malformed. */
function readRecords() {
  const problems = [];
  const records = [];
  const seen = new Map();
  for (const file of readdirSync(DIR).filter((name) => /^\d{4}-.+\.md$/.test(name)).sort()) {
    const number = file.slice(0, 4);
    if (seen.has(number)) problems.push(`ADR ${number} is used twice: ${seen.get(number)} and ${file}; give the newer one the next free number.`);
    seen.set(number, file);
    const lines = readFileSync(path.join(DIR, file), "utf8").split("\n");
    const title = lines.find((line) => line.startsWith("# "));
    const titleMatch = title?.match(/^# (\d{4})\. (.+)$/);
    if (!titleMatch) problems.push(`${file}: the first heading must be "# ${number}. Title".`);
    else if (titleMatch[1] !== number) problems.push(`${file}: its heading says ${titleMatch[1]}, its file name ${number}.`);
    const status = lines.find((line) => line.startsWith("**Status:**"));
    if (!status) problems.push(`${file}: no "**Status:** …" line.`);
    if (titleMatch && status) {
      records.push({ number, file, title: titleMatch[2], status: shortStatus(status.slice("**Status:**".length)) });
    }
  }
  return { records, problems };
}

const cell = (text) => text.replace(/\|/g, "\\|");

function table(records) {
  return [
    "| # | Decision | Status |",
    "|---|---|---|",
    ...records.map((r) => `| [${r.number}](${r.file}) | ${cell(r.title)} | ${cell(r.status)} |`),
  ].join("\n");
}

/** The README with its table replaced, or a problem when the markers are missing. */
function withTable(readme, records) {
  const start = readme.indexOf(START);
  const end = readme.indexOf(END);
  if (start < 0 || end < start) return { problem: `docs/adr/README.md needs the lines ${START} and ${END} around the table.` };
  return { text: `${readme.slice(0, start + START.length)}\n${table(records)}\n${readme.slice(end)}` };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const { records, problems } = readRecords();
  const readme = readFileSync(README, "utf8");
  const next = withTable(readme, records);
  if (next.problem) problems.push(next.problem);
  if (problems.length > 0) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  if (next.text === readme) {
    console.log(`docs/adr/README.md lists all ${records.length} records.`);
  } else if (check) {
    console.error("docs/adr/README.md's table is stale: run `npm run docs` (never edit the table by hand).");
    process.exit(1);
  } else {
    writeFileSync(README, next.text);
    console.log(`docs/adr/README.md: table rebuilt, ${records.length} records.`);
  }
}
