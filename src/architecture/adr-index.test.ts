// The table of decisions in docs/adr/README.md is built by `npm run docs`
// (scripts/adr-index.mjs) from each record's title and Status line, so it is never
// edited by hand and never conflicts between branches. This fails when it is
// stale, when two records share a number, or when a record lacks either line.

import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const SCRIPT = fileURLToPath(new URL("../../scripts/adr-index.mjs", import.meta.url));

function run(...args: string[]) {
  const result = spawnSync(process.execPath, [SCRIPT, ...args], { encoding: "utf8" });
  return { status: result.status, output: `${result.stdout}${result.stderr}` };
}

function folder(records: Record<string, string>) {
  const dir = mkdtempSync(path.join(tmpdir(), "adr-index-"));
  const readme = "# Records\n\n<!-- adr-index: generated by `npm run docs`; do not edit by hand -->\n<!-- /adr-index -->\n";
  writeFileSync(path.join(dir, "README.md"), readme);
  for (const [file, text] of Object.entries(records)) writeFileSync(path.join(dir, file), text);
  return dir;
}

const record = (n: string, title: string, status: string) => `# ${n}. ${title}\n\n**Status:** ${status}\n`;

describe("the ADR index", () => {
  it("is current: run `npm run docs` after adding or changing a record", () => {
    const { status, output } = run("--check");
    expect(output).toContain("lists all");
    expect(status).toBe(0);
  });

  it("refuses two records with one number", () => {
    const dir = folder({
      "0001-first.md": record("0001", "First", "Accepted."),
      "0001-second.md": record("0001", "Second", "Accepted."),
    });
    try {
      const { status, output } = run("--check", "--dir", dir);
      expect(status).toBe(1);
      expect(output).toContain("ADR 0001 is used twice");
    } finally {
      rmSync(dir, { recursive: true });
    }
  });

  it("builds the table, keeping only what changed a record from its Status line", () => {
    const dir = folder({
      "0001-first.md": record("0001", "First", "Accepted (asked by the owner); built in stages. Amended by 0002: more keys."),
      "0002-second.md": record("0002", "Second | with a bar", "Proposed."),
    });
    try {
      expect(run("--check", "--dir", dir).status).toBe(1);
      expect(run("--dir", dir).status).toBe(0);
      expect(run("--check", "--dir", dir).status).toBe(0);
      const readme = readFileSync(path.join(dir, "README.md"), "utf8");
      expect(readme).toContain("| [0001](0001-first.md) | First | Accepted; built in stages; amended by 0002 |");
      expect(readme).toContain("| [0002](0002-second.md) | Second \\| with a bar | Proposed |");
    } finally {
      rmSync(dir, { recursive: true });
    }
  });

  it("refuses a record without a Status line", () => {
    const dir = folder({ "0001-first.md": "# 0001. First\n\nNo status here.\n" });
    try {
      const { status, output } = run("--check", "--dir", dir);
      expect(status).toBe(1);
      expect(output).toContain("no \"**Status:** …\" line");
    } finally {
      rmSync(dir, { recursive: true });
    }
  });
});
